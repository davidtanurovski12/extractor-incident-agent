"""Fetch a bounded source snapshot for read-only runtime inspection."""

import io
import json
import os
import tarfile
import tempfile
from functools import lru_cache
from pathlib import Path, PurePosixPath
from urllib.parse import quote
from urllib.request import Request, urlopen

import boto3


REPOSITORY = "devrev/airsync-metis"
MAX_ARCHIVE_BYTES = 100_000_000
MAX_UNPACKED_BYTES = 200_000_000


def _github_token() -> str | None:
    secret_id = os.environ.get("INCIDENT_GITHUB_TOKEN_SECRET_ID", "incident-repro/jira")
    if not secret_id:
        return None
    region = os.environ.get("INCIDENT_GITHUB_SECRET_REGION", "us-west-2")
    secret = boto3.client("secretsmanager", region_name=region).get_secret_value(
        SecretId=secret_id)["SecretString"]
    try:
        parsed = json.loads(secret)
    except json.JSONDecodeError:
        return secret.strip()
    if isinstance(parsed, dict):
        token = parsed.get("github_token") or parsed.get("token")
        if isinstance(token, str) and token.strip():
            return token.strip()
    raise ValueError("GitHub token secret must be a token string or contain github_token")


@lru_cache(maxsize=1)
def source_root() -> Path:
    """Download the configured revision once per process into temporary storage."""
    revision = os.environ.get("INCIDENT_SOURCE_REF", "main")
    url = f"https://api.github.com/repos/{REPOSITORY}/tarball/{quote(revision, safe='')}"
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "extractor-incident-agent"}
    token = _github_token()
    if token:
        headers["Authorization"] = f"Bearer {token}"
    with urlopen(Request(url, headers=headers), timeout=30) as response:
        archive = response.read(MAX_ARCHIVE_BYTES + 1)
    if len(archive) > MAX_ARCHIVE_BYTES:
        raise ValueError("GitHub source archive exceeds the download limit")

    target = Path(tempfile.mkdtemp(prefix="incident-source-"))
    size = 0
    try:
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
            for member in tar:
                parts = PurePosixPath(member.name).parts[1:]  # archive root is generated by GitHub
                if not parts or any(part in (".", "..") for part in parts):
                    continue
                if not member.isfile():
                    continue  # never materialize symlinks or special files
                size += member.size
                if size > MAX_UNPACKED_BYTES:
                    raise ValueError("GitHub source archive exceeds the unpacked limit")
                destination = target.joinpath(*parts)
                destination.parent.mkdir(parents=True, exist_ok=True)
                with tar.extractfile(member) as source, destination.open("wb") as output:
                    while chunk := source.read(1024 * 1024):
                        output.write(chunk)
    except Exception:
        import shutil
        shutil.rmtree(target)
        raise
    return target
